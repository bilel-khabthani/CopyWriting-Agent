"""Phase 4 helper: turn a pipeline Result into Telegram-ready messages.

Responsibilities:
- Build a readable message from the strategy brief + script.
- Convert the model's markdown into Telegram legacy-markdown that renders.
- Split text at Telegram's 4096-character limit without breaking layout.
"""

import re

from formats import get_format

TELEGRAM_LIMIT = 4096


def _convert_markdown(text: str) -> str:
    """Convert model markdown (# headings, **bold**) to Telegram legacy markdown."""
    out_lines = []
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("#"):
            title = stripped.lstrip("#").strip()
            out_lines.append("*{0}*".format(title))
        else:
            out_lines.append(line)
    text = "\n".join(out_lines)
    text = re.sub(r"\*\*(.+?)\*\*", r"*\1*", text)
    return text


def markdown_to_plain(text: str) -> str:
    """Strip markdown markers for a safe plain-text fallback."""
    text = re.sub(r"\*\*(.+?)\*\*", r"\1", text)
    text = re.sub(r"\*(.+?)\*", r"\1", text)
    text = re.sub(r"^#{1,6}\s*", "", text, flags=re.MULTILINE)
    return text


def _join(items) -> str:
    if not items:
        return "-"
    return " | ".join(str(item).strip() for item in items)


def format_internal(result) -> str:
    """Full view for the operator: strategy brief + script + meta."""
    strategy = result.strategy or {}
    meta = get_format(getattr(result, "format", "video_ad"))
    name = meta["name"] if meta else "Deliverable"
    parts = [
        "*STRATEGY BRIEF*",
        "Audience: {0}".format(strategy.get("audience", "-")),
        "Emotion target: {0}".format(strategy.get("emotion_target", "-")),
        "Positioning: {0}".format(strategy.get("positioning", "-")),
        "Pains: {0}".format(_join(strategy.get("pains"))),
        "Desires: {0}".format(_join(strategy.get("desires"))),
        "Hook angles: {0}".format(_join(strategy.get("hook_angles"))),
        "",
        "*{0}*".format(name.upper()),
        _convert_markdown(result.script or ""),
        "",
        "---",
        "_Generated by {0} in {1:.1f}s_".format(
            result.scriptwriter_model, result.seconds
        ),
    ]
    return "\n".join(parts)


def format_client(result) -> str:
    """Clean deliverable for the client: header + script + light branding."""
    brief = getattr(result, "brief", {}) or {}
    brand = (brief.get("brand") or "").strip()
    platform = (brief.get("platform") or "").strip()
    meta = get_format(getattr(result, "format", "video_ad"))
    name = meta["name"] if meta else "Copy"

    header = "*{0} - {1}*".format(brand, name) if brand else "*{0}*".format(name)
    parts = [header]
    if platform:
        parts.append("_Platform: {0}_".format(platform))
    parts += [
        "",
        _convert_markdown(result.script or ""),
        "",
        "_Prepared with AdScript Studio_",
    ]
    return "\n".join(parts)


# Backwards-compatible alias (older callers import format_result).
format_result = format_internal


def split_message(text: str, limit: int = TELEGRAM_LIMIT) -> list:
    """Split text into chunks of <= limit chars, keeping code fences balanced."""
    if len(text) <= limit:
        return [text]

    chunks = []
    current = []
    current_len = 0
    in_code = False

    for raw_line in text.split("\n"):
        segment = raw_line + "\n"
        is_fence = raw_line.strip().startswith("```")

        if current_len + len(segment) > limit and current:
            block = "".join(current)
            if in_code:
                block += "```\n"
            chunks.append(block.rstrip("\n"))
            current = ["```\n"] if in_code else []
            current_len = 4 if in_code else 0

        current.append(segment)
        current_len += len(segment)
        if is_fence:
            in_code = not in_code

    if current:
        chunks.append("".join(current).rstrip("\n"))
    return chunks
